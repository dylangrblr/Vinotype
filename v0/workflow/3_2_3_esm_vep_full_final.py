"""Helper Functions for ESM Analysis"""

import string
from Bio import SeqIO
import re
import pandas as pd

def remove_insertions(sequence: str) -> str:
    deletekeys = dict.fromkeys(string.ascii_lowercase)
    deletekeys["."] = None
    deletekeys["*"] = None
    translation = str.maketrans(deletekeys)
    return sequence.translate(translation)

def find_matching_files(fasta_dir, var_dir):
    matches = []

    #List all protein files in fasta input dir
    protein_files = [f for f in os.listdir(fasta_dir) if f.endswith('.seq.fasta')]

    for protein_file in protein_files:
        #Extract base name
        base_name = protein_file.replace('.seq.fasta', '')
        var_filename = f"{base_name}.var.txt"
        var_file = os.path.join(var_dir, var_filename)

        print(f"🔍 Looking for: {protein_file} -> {var_filename}")
        print(f"    Checking: {var_file}")
        print(f"    Exists: {os.path.exists(var_file)}")

        if os.path.exists(var_file):
            matches.append((protein_file, var_file, base_name))
            print(f"    ✅ Match found!")
        else:
            print(f"    ❌ No match found")

    return matches

def load_protein_sequence(fasta_file):
    try:
        with open(fasta_file, 'r') as f:
            for record in SeqIO.parse(f, "fasta"):
                return str(record.seq)
        return None
    except Exception as e:
        print(f"❌ Error loading {fasta_file}: {e}")
        return None

def load_variants(variant_file):
    variants = []
    try:
        print(f"📝 Reading variants from: {variant_file}")
        with open(variant_file, 'r') as f:
            for line_num, line in enumerate(f, 1):
                line = line.strip()
                print(f"    Line {line_num}: '{line}'")
                if not line or line.startswith('#'):
                    continue
                match = re.match(r'^([A-Z])(\d+)([A-Z])$', line)
                if match:
                    ref_aa, pos, alt_aa = match.groups()
                    variants.append((ref_aa, int(pos), alt_aa))
                    print(f"    ✅ Valid variant: {ref_aa}{pos}{alt_aa}")
                else:
                    print(f"    ❌ Invalid format: '{line}'")
        return variants
    except Exception as e:
        print(f"❌ Error loading {variant_file}: {e}")
        return []

