import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd
import numpy as np

def analyze_results(results_df):
    #Summary stats
    total_variants = len(results_df)
    deleterious_count = len(results_df[results_df['score'] > 0])
    tolerated_count = len(results_df[results_df['score'] <= 0])

    print(f"Total variants analyzed: {total_variants}")
    print(f"Predicted deleterious: {deleterious_count} ({deleterious_count/total_variants*100:.1f}%)")
    print(f"Predicted tolerated: {tolerated_count} ({tolerated_count/total_variants*100:.1f}%)")

    #Visualisations
    plt.figure(figsize=(10, 6))
    sns.histplot(results_df['score'], bins=20, color='skyblue', edgecolor='black')
    plt.axvline(x=0, color='red', linestyle='--', label='Neutral threshold')
    plt.xlabel('ESM Score')
    plt.ylabel('Frequency')
    plt.title('Distribution of ESM Scores')
    plt.legend()
    plt.show()

    #Effect predictions
    effect_counts = results_df.apply(lambda row: 'Deleterious' if row['score'] > 0 else 'Tolerated', axis=1).value_counts()
    colors = ['lightcoral' if x == 'Deleterious' else 'lightgreen' for x in effect_counts.index]
    plt.figure(figsize=(8, 8))
    plt.pie(effect_counts.values, labels=effect_counts.index, autopct='%1.1f%%', colors=colors)
    plt.title('Predicted Effect Distribution')
    plt.show()

    #Scores by protein
    if len(results_df['protein'].unique()) > 1:
        plt.figure(figsize=(10, 6))
        sns.boxplot(x='protein', y='score', data=results_df)
        plt.title('ESM Scores by Protein')
        plt.xticks(rotation=45)
        plt.show()

def save_results(results_df, output_filename):
    results_df.to_csv(output_filename, index=False)
    print(f"\n💾 Results saved to '{output_filename}'")
    

