import torch
from esm import Alphabet, pretrained, MSATransformer
import pandas as pd
from tqdm import tqdm

def label_row(row, sequence, token_probs, alphabet, offset_idx):
    wt, pos, mt = row
    pos_adj = pos - offset_idx

    print(f"    🔍 Checking position {pos} (adjusted: {pos_adj}) in sequence of length {len(sequence)}")
    print(f"    Expected: {wt}, Found: {sequence[pos_adj] if 0 <= pos_adj < len(sequence) else 'OUT_OF_BOUNDS'}")

    assert 0 <= pos_adj < len(sequence), f"Position {pos_adj} is out of bounds for sequence of length {len(sequence)}"
    assert sequence[pos_adj] == wt, f"The listed wildtype {wt} does not match the provided sequence {sequence[pos_adj]} at position {pos}"

    wt_encoded = alphabet.get_idx(wt)
    mt_encoded = alphabet.get_idx(mt)
    score = token_probs[0, 1 + pos_adj, mt_encoded] - token_probs[0, 1 + pos_adj, wt_encoded]
    return score.item()

def compute_pppl(row, sequence, model, alphabet, offset_idx):
    wt, pos, mt = row
    pos_adj = pos - offset_idx
    assert sequence[pos_adj] == wt, "The listed wildtype does not match the provided sequence"
    sequence = sequence[:pos_adj] + mt + sequence[(pos_adj + 1):]
    data = [("protein1", sequence)]
    batch_converter = alphabet.get_batch_converter()
    batch_labels, batch_strs, batch_tokens = batch_converter(data)
    batch_tokens = batch_tokens.cuda()
    log_probs = []
    for i in range(1, len(sequence) - 1):
        batch_tokens_masked = batch_tokens.clone()
        batch_tokens_masked[0, i] = alphabet.mask_idx
        with torch.no_grad():
            token_probs = torch.log_softmax(model(batch_tokens_masked)["logits"], dim=-1)
        log_probs.append(token_probs[0, i, alphabet.get_idx(sequence[i])].item())
    return sum(log_probs)

def process_protein(fasta_path, var_path, model_location, scoring_strategy, offset_idx, nogpu):
    print(f"\n📄 Processing protein: {os.path.basename(fasta_path)}")

    #Load protein sequence
    print(f"🧬 Loading protein sequence from: {fasta_path}")
    sequence = load_protein_sequence(fasta_path)
    if not sequence:
        print(f"❌ Failed to load protein sequence from {fasta_path}")
        return []

    print(f"✅ Loaded protein sequence of length: {len(sequence)} amino acids")
    print(f"🧬 Sequence preview: {sequence[:50]}...")

    #Load variants
    print(f"📝 Loading variants from: {var_path}")
    variants = load_variants(var_path)
    if not variants:
        print(f"❌ No variants loaded from {var_path}")
        return []

    print(f"✅ Loaded {len(variants)} variants")
    print(f"📝 First variant: {variants[0]}")

    #Process variants
    device = torch.device("cuda" if torch.cuda.is_available() and not nogpu else "cpu")
    print(f"🚀 Using device: {device}")

    results = []

    for model_loc in model_location:
        print(f"\n🧠 Loading model: {model_loc}")
        try:
            model, alphabet = pretrained.load_model_and_alphabet(model_loc)
            model = model.to(device)
            model.eval()
            print(f"✅ Model loaded successfully: {model_loc}")
        except Exception as e:
            print(f"❌ Error loading model {model_loc}: {e}")
            continue

        if scoring_strategy == "masked-marginals":
            print("🔄 Using masked-marginals scoring strategy")
            data = [("protein1", sequence)]
            batch_converter = alphabet.get_batch_converter()
            batch_labels, batch_strs, batch_tokens = batch_converter(data)
            batch_tokens = batch_tokens.to(device)

            all_token_probs = []
            for i in tqdm(range(batch_tokens.size(1)), desc="Processing positions"):
                batch_tokens_masked = batch_tokens.clone()
                batch_tokens_masked[0, i] = alphabet.mask_idx
                with torch.no_grad():
                    token_probs = torch.log_softmax(model(batch_tokens_masked)["logits"], dim=-1)
                all_token_probs.append(token_probs[:, i])
            token_probs = torch.cat(all_token_probs, dim=0).unsqueeze(0)

            print(f"🎯 Processing {len(variants)} variants")
            for wt, pos, mt in variants:
                print(f"  Processing variant: {wt}{pos}{mt}", end="")
                try:
                    score = label_row((wt, pos, mt), sequence, token_probs, alphabet, offset_idx)
                    print(f" ✅ Score: {score:.3f}")
                    #Properly append results
                    results.append({
                        'protein': os.path.basename(fasta_path),
                        'variant': f"{wt}{pos}{mt}",
                        'position': pos,
                        'ref_aa': wt,
                        'alt_aa': mt,
                        'score': score,
                        'model': model_loc
                    })
                except Exception as e:
                    print(f" ❌ Error: {e}")

    print(f"\n✅ Finished processing protein: {os.path.basename(fasta_path)}")
    print(f"  Total variants processed: {len(results)}")

    return results

