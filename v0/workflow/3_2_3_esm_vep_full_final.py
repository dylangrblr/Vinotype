"""Main Processing Function"""

def main(fasta_dir, var_dir, model_location, scoring_strategy, offset_idx, nogpu):
    #Find matching files
    matches = find_matching_files(fasta_dir, var_dir)

    print(f"\n📊 Found {len(matches)} matching file pairs")

    all_results = []

    for protein_file, var_file, base_name in matches:
        print(f"\n🔄 Processing: {base_name}")
        results = process_protein(
            os.path.join(fasta_dir, protein_file),
            var_file,
            model_location,
            scoring_strategy,
            offset_idx,
            nogpu
        )
        if results:
            all_results.extend(results)

    return pd.DataFrame(all_results)

